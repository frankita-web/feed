const ALL = new Set(Object.values(PINTEREST_REFS).flat());

/** Foto que se puso sola desde Pinterest (no una que Franca subió). */
export const isPinterestPhoto = (id: string) => ALL.has(id);

const SEARCH = /pinterest\.[a-z.]+\/search\/pins\/\?q=([^\s&#]+)/gi;

/**
 * Fotos de referencia para una idea según los links de Pinterest que tiene: las primeras de cada
 * búsqueda, repartidas para que sean 5 o 6 en total.
 */
export function pinterestPhotos(text: string): string[] {
  const queries = [...new Set([...text.matchAll(SEARCH)].map((m) => decode(m[1])))];
  const lists = queries.map((q) => PINTEREST_REFS[q]).filter((list) => list?.length);
  if (!lists.length) return [];
  const each = lists.length === 1 ? 5 : lists.length === 2 ? 3 : 2;
  return [...new Set(lists.flatMap((list) => list.slice(0, each)))].slice(0, 6);
}

function decode(query: string) {
  try {
    return decodeURIComponent(query.replace(/\+/g, " ")).trim().toLowerCase();
  } catch {
    return query;
  }
}
